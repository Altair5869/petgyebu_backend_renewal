CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR(10) NOT NULL,
  provider_user_id VARCHAR(255) NOT NULL,
  pet_type VARCHAR(10),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_login_time TIMESTAMPTZ NOT NULL,
  active_session_id UUID,
  refresh_token_hash VARCHAR(255),
  refresh_token_expires_at TIMESTAMPTZ,
  CONSTRAINT uq_users_provider_identity UNIQUE (provider, provider_user_id)
);

CREATE TABLE expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  amount BIGINT NOT NULL,
  expense_date DATE NOT NULL,
  category VARCHAR(20) NOT NULL,
  memo TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_expenses_user_date_id
  ON expenses (user_id, expense_date DESC, id DESC);

CREATE TABLE monthly_budgets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  budget_month DATE NOT NULL,
  amount BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_monthly_budgets_user_month UNIQUE (user_id, budget_month)
);
